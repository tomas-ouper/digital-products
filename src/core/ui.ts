export function starsText(n: number, max = 3) {
  return '★'.repeat(n) + '☆'.repeat(Math.max(0, max - n));
}

export function shuffle<T>(arr: T[]): T[] {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
